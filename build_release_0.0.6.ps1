        $cred = $gp.StandardOutput.ReadToEnd() -split "`n"
        $gp.WaitForExit(60000) | Out-Null
        $tok = (($cred | Where-Object { $_ -like "password=*" }) -replace "^password=", "").Trim()
        if (-not $tok) { throw "no GitHub credential in Git Credential Manager - sign in with GitHub Desktop/git first" }
        $h = @{ Authorization = "token $tok"; "User-Agent" = "AppliedAstrology-release"; Accept = "application/vnd.github+json" }
        $api = "https://api.github.com/repos/$Owner/$RepoName"
        $rel = $null
        try { $rel = Invoke-RestMethod -Headers $h -Uri "$api/releases/tags/v$Ver" -Method Get } catch { }
        $notesFile = Join-Path $Repo "docs\RELEASE_NOTES_$Ver.md"
        $notes = if (Test-Path $notesFile) { Get-Content $notesFile -Raw -Encoding UTF8 } else { "Applied Astrology $Ver" }
        if (-not $rel) {
            try { $rel = (Invoke-RestMethod -Headers $h -Uri "$api/releases?per_page=50" -Method Get) | Where-Object { $_.tag_name -eq "v$Ver" } | Select-Object -First 1 } catch { }
        }
        if (-not $rel) {
            $body = @{ tag_name = "v$Ver"; name = "Applied Astrology v$Ver"; body = [string]$notes; draft = $false; prerelease = $false } | ConvertTo-Json -Depth 4
            try { $rel = Invoke-RestMethod -Headers $h -Uri "$api/releases" -Method Post -Body ([Text.Encoding]::UTF8.GetBytes($body)) -ContentType "application/json; charset=utf-8" }
            catch {
                $detail = $_.ErrorDetails.Message
                if (-not $detail) { try { $sr = New-Object IO.StreamReader($_.Exception.Response.GetResponseStream()); $detail = $sr.ReadToEnd() } catch { } }
                Say "  create release failed: $detail" "ERR"
                # retry with a short body (in case the notes are rejected)
                $body = @{ tag_name = "v$Ver"; name = "Applied Astrology v$Ver"; body = "Applied Astrology v$Ver - see docs/RELEASE_NOTES_$Ver.md"; draft = $false; prerelease = $false } | ConvertTo-Json
                $rel = Invoke-RestMethod -Headers $h -Uri "$api/releases" -Method Post -Body ([Text.Encoding]::UTF8.GetBytes($body)) -ContentType "application/json; charset=utf-8"
            }
        }
        try { $patch = @{ body = [string]$notes; name = "Applied Astrology v$Ver" } | ConvertTo-Json -Depth 4; $rel = Invoke-RestMethod -Headers $h -Uri "$api/releases/$($rel.id)" -Method Patch -Body ([Text.Encoding]::UTF8.GetBytes($patch)) -ContentType "application/json; charset=utf-8" } catch { Say "  release notes update failed: $($_.Exception.Message)" "ERR" }
        Say "  release id $($rel.id) $($rel.html_url)"
        $assets = @(Get-ChildItem $Out -File | Where-Object { $_.Extension -in ".apk", ".zip", ".exe", ".msi", ".appxbundle", ".cer", ".txt", ".bat" })
        # test videos (kept out of git because of the 100 MB file limit) are attached to the release
        foreach ($v in (Get-ChildItem $Reports -Recurse -Filter *.mp4)) {
            $nm = "test-video-" + ($v.Directory.Name -replace "[^A-Za-z0-9_.-]", "_") + "-" + [IO.Path]::GetFileNameWithoutExtension($v.Name) + ".mp4"   # v0.0.6: keep part2/part3 (same folder) as separate assets
            $dst = Join-Path $Work $nm; Copy-Item $v.FullName $dst -Force; $assets += Get-Item $dst
        }
        foreach ($f in $assets) {
            $old = $rel.assets | Where-Object { $_.name -eq $f.Name }
            # skip only when GitHub's sha256 digest of the uploaded asset equals the local file (same size is NOT enough: a rebuilt APK can keep its size)
            if ($old -and $old.state -eq "uploaded" -and $old.digest -and ($old.digest -eq ("sha256:" + (Sha $f.FullName)))) { Say ("  already uploaded {0} (sha256 match) - skip" -f $f.Name); continue }
            if ($old) { Invoke-RestMethod -Headers $h -Uri "$api/releases/assets/$($old.id)" -Method Delete | Out-Null }
            $ct = switch ($f.Extension) { ".apk" { "application/vnd.android.package-archive" } ".zip" { "application/zip" } ".msi" { "application/x-msi" } ".txt" { "text/plain" } ".md" { "text/markdown" } default { "application/octet-stream" } }
            $up = "https://uploads.github.com/repos/$Owner/$RepoName/releases/$($rel.id)/assets?name=$([Uri]::EscapeDataString($f.Name))"
            Say ("  uploading {0} ({1:N2} MB)" -f $f.Name, ($f.Length / 1MB))
            $ok = $false
            for ($try = 1; $try -le 4 -and -not $ok; $try++) {
                try { Invoke-RestMethod -Headers $h -Uri $up -Method Post -InFile $f.FullName -ContentType $ct -TimeoutSec 1800 | Out-Null; $ok = $true }
                catch {
                    Say "  upload attempt $try of $($f.Name) failed: $($_.Exception.Message)" "ERR"
                    Start-Sleep (10 * $try)
                    # a half-finished upload leaves a broken asset with the same name: remove it before retrying
                    try { $cur = Invoke-RestMethod -Headers $h -Uri "$api/releases/$($rel.id)" -Method Get; $bad = $cur.assets | Where-Object { $_.name -eq $f.Name }; if ($bad) { Invoke-RestMethod -Headers $h -Uri "$api/releases/assets/$($bad.id)" -Method Delete | Out-Null } } catch { }
                }
            }
            if (-not $ok) { Say "  giving up on $($f.Name)" "ERR" }
        }
        # Verify
        $rel = Invoke-RestMethod -Headers $h -Uri "$api/releases/$($rel.id)" -Method Get
        $missing = @()
        foreach ($f in $assets) {
            $a = $rel.assets | Where-Object { $_.name -eq $f.Name }
            $dig = if ($a -and $a.digest) { $a.digest } else { "" }
            if (-not $a -or $a.size -ne $f.Length -or ($dig -and $dig -ne ("sha256:" + (Sha $f.FullName)))) { $missing += $f.Name } else { Say ("  verified {0} {1} bytes state={2} {3}" -f $a.name, $a.size, $a.state, $dig) "OK" }
        }
        "release_url=$($rel.html_url)" | Set-Content (Join-Path $LogDir "release_url.txt")
        if ($missing.Count) { throw "assets missing/mismatch: $($missing -join ', ')" }
        Say "  Release: $($rel.html_url)" "OK"
    }
    # v0.0.6: home page + privacy policy (docs/index.html, docs/privacy.html) on GitHub Pages, set as the repository "About" website
    Step "32_github_pages_about" {
        $tok = Get-GhToken; if (-not $tok) { throw "no GitHub credential" }
        $h = @{ Authorization = "token $tok"; "User-Agent" = "AppliedAstrology-release"; Accept = "application/vnd.github+json" }
        $api = "https://api.github.com/repos/$Owner/$RepoName"
        $site = "https://$Owner.github.io/$RepoName/"
        $pg = $null; try { $pg = Invoke-RestMethod -Headers $h -Uri "$api/pages" -Method Get } catch { }
        $src = @{ source = @{ branch = "main"; path = "/docs" } } | ConvertTo-Json -Depth 4
        if (-not $pg) { try { $pg = Invoke-RestMethod -Headers $h -Uri "$api/pages" -Method Post -Body $src -ContentType "application/json" ; Say "  GitHub Pages enabled (main /docs)" "OK" } catch { Say "  enable Pages failed: $($_.ErrorDetails.Message)" "ERR" } }
        elseif ($pg.source.path -ne "/docs" -or $pg.source.branch -ne "main") { try { Invoke-RestMethod -Headers $h -Uri "$api/pages" -Method Put -Body $src -ContentType "application/json" | Out-Null; Say "  GitHub Pages source set to main /docs" "OK" } catch { Say "  update Pages failed: $($_.ErrorDetails.Message)" "ERR" } }
        else { Say "  GitHub Pages already on main /docs: $($pg.html_url)" "OK" }
        $about = @{ homepage = $site; description = "Applied Astrology (Tử Vi Ứng Dụng) - native Tu Vi chart, lunar calendar, Buu Dinh library, Liquid Glass UI, 68 languages. Android 6.0+ / Windows 7+. Home: $site - Privacy: ${site}privacy.html" } | ConvertTo-Json
        $repoInfo = Invoke-RestMethod -Headers $h -Uri $api -Method Patch -Body ([Text.Encoding]::UTF8.GetBytes($about)) -ContentType "application/json; charset=utf-8"
        Say "  About website: $($repoInfo.homepage)" "OK"
        try { Invoke-RestMethod -Headers $h -Uri "$api/topics" -Method Put -Body (@{ names = @("tu-vi", "astrology", "lunar-calendar", "android", "windows", "liquid-glass", "vietnamese") } | ConvertTo-Json) -ContentType "application/json" | Out-Null } catch { }
        # wait for the first Pages build, then check both pages answer
        for ($i = 0; $i -lt 20; $i++) {
            try { $b = Invoke-RestMethod -Headers $h -Uri "$api/pages/builds/latest" -Method Get; Say "  Pages build: $($b.status)"; if ($b.status -in @("built", "errored")) { break } } catch { }
            Start-Sleep 15
        }
        foreach ($u in @($site, "${site}privacy.html")) {
            try { $r = Invoke-WebRequest -Uri $u -UseBasicParsing -TimeoutSec 60; Say ("  {0} -> HTTP {1}, {2} bytes" -f $u, $r.StatusCode, $r.RawContentLength) "OK" } catch { Say "  $u not reachable yet: $($_.Exception.Message)" "ERR" }
        }
        "pages_url=$site" | Set-Content (Join-Path $LogDir "pages_url.txt")
    }
}

$Summary.finished = (Get-Date).ToString("s")
$Summary.failed = $script:Failed
[IO.File]::WriteAllText($StatusFile, ($Summary | ConvertTo-Json -Depth 6), $Utf8)
if ($script:Failed.Count) { Say "=== Finished with failures: $($script:Failed -join ', ') ===" "ERR" } else { Say "=== ALL DONE ===" "OK" }
