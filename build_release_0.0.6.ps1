            $badge = Run "$($T.bt)\aapt2.exe" @("dump", "badging", $signed) "badging" -IgnoreExit
            Copy-Item $signed $final -Force
            Say ("  {0}: {1:N2} MB  {2}" -f $abi, ((Get-Item $final).Length / 1MB), ($badge | Select-Object -First 1))
        }
    }
