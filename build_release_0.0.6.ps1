# v0.0.5: frame statistics while scrolling the Settings screen (long list of glass cards) - used to compare 0.0.4 vs 0.0.5
function Measure-Gfx([string]$serial, [string]$file, [string]$what) {
    $pkg = "com.appliedastrology.tuvi"
    Adb @("-s", $serial, "shell", "am", "force-stop", $pkg) -Quiet | Out-Null
    Adb @("-s", $serial, "shell", "am", "broadcast", "-a", "android.intent.action.CLOSE_SYSTEM_DIALOGS") -Quiet | Out-Null
    Adb @("-s", $serial, "shell", "am", "start", "-S", "-W", "-n", "$pkg/.MainActivity", "--es", "tab", "settings") -Quiet | Out-Null
    Start-Sleep 7
    $size = ((Adb @("-s", $serial, "shell", "wm", "size") -Quiet) -join " ")
    $w = 1080; $h = 1920; if ($size -match "(\d+)x(\d+)\s*$") { $w = [int]$Matches[1]; $h = [int]$Matches[2] }
    Adb @("-s", $serial, "shell", "dumpsys", "gfxinfo", $pkg, "reset") -Quiet | Out-Null
    $x = [int]($w / 2); $y1 = [int]($h * 0.72); $y2 = [int]($h * 0.32)
    for ($i = 0; $i -lt 6; $i++) { Adb @("-s", $serial, "shell", "input", "swipe", "$x", "$y1", "$x", "$y2", "260") -Quiet | Out-Null; Start-Sleep -Milliseconds 400 }
    for ($i = 0; $i -lt 6; $i++) { Adb @("-s", $serial, "shell", "input", "swipe", "$x", "$y2", "$x", "$y1", "260") -Quiet | Out-Null; Start-Sleep -Milliseconds 400 }
    Start-Sleep 1
    $g = Adb @("-s", $serial, "shell", "dumpsys", "gfxinfo", $pkg) -Quiet
    $g | Set-Content $file -Encoding UTF8
    $txt = $g -join "`n"; $o = [ordered]@{ what = $what; frames = $null; janky = $null; jankyPct = $null; p50 = $null; p90 = $null; p95 = $null; p99 = $null }
    if ($txt -match "Total frames rendered:\s*(\d+)") { $o.frames = [int]$Matches[1] }
    if ($txt -match "Janky frames:\s*(\d+)\s*\(([\d.]+)%\)") { $o.janky = [int]$Matches[1]; $o.jankyPct = [double]$Matches[2] }
    foreach ($p in "50", "90", "95", "99") { if ($txt -match "$($p)th percentile:\s*(\d+)ms") { $o["p$p"] = [int]$Matches[1] } }
    Say ("  gfx {0}: frames={1} janky={2} ({3}%) p50={4}ms p90={5}ms p99={6}ms" -f $what, $o.frames, $o.janky, $o.jankyPct, $o.p50, $o.p90, $o.p99)
    return $o
}
